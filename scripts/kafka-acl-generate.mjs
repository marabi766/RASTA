#!/usr/bin/env node
/**
 * Writes the broker bootstrap files from the topology contracts (RUN-006):
 *
 *   infrastructure/docker/kafka/broker-acls.json   principals and ACLs
 *   infrastructure/docker/kafka/principals.txt     one principal per line
 *
 * Both are committed and applied by the local and CI bootstrap alike
 * (`infrastructure/docker/kafka/`). `packages/contracts` fails its tests when
 * they drift from what `brokerAclDocument('development')` generates, so run
 * this after any change to TOPIC_PRODUCERS or TOPIC_CONSUMERS:
 *
 *   pnpm kafka:acl:generate
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const contracts = require(resolve(root, 'packages/contracts/dist/index.js'));

const document = contracts.brokerAclDocument('development');
const dir = resolve(root, 'infrastructure/docker/kafka');

writeFileSync(resolve(dir, 'broker-acls.json'), `${JSON.stringify(document, null, 2)}\n`);
writeFileSync(
  resolve(dir, 'principals.txt'),
  [
    '# Generated by `pnpm kafka:acl:generate` from TOPIC_PRODUCERS and TOPIC_CONSUMERS (RUN-006).',
    '# Every principal the broker holds a SCRAM-SHA-512 credential for, besides the admin.',
    '# Each reads its password from KAFKA_SASL_PASSWORD_<NAME> (fleet-service -> _FLEET).',
    ...document.principals,
    '',
  ].join('\n'),
);
process.stdout.write(
  `kafka acl: ${document.principals.length} principals, ${document.acls.length} bindings written to ${dir}\n`,
);
