#!/usr/bin/env node
/**
 * Writes the broker bootstrap files from the topology contracts (RUN-006):
 *
 *   infrastructure/docker/kafka/broker-acls.<profile>.json   principals and ACLs
 *   infrastructure/docker/kafka/principals.<profile>.txt     one principal per line
 *   infrastructure/docker/kafka/topics.txt                    every topic to create
 *
 * for each profile: `development` (compose and CI) and `deployment` (without
 * the development-only principals). All are committed; `packages/contracts`
 * fails its tests when they drift from what the contracts generate, so run
 * this after any change to TOPIC_PRODUCERS or TOPIC_CONSUMERS:
 *
 *   pnpm kafka:acl:generate
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const contracts = require(resolve(root, 'packages/contracts/dist/index.js'));
const dir = resolve(root, 'infrastructure/docker/kafka');

for (const profile of contracts.BROKER_PROFILES) {
  const document = contracts.brokerAclDocument(profile);
  writeFileSync(
    resolve(dir, `broker-acls.${profile}.json`),
    `${JSON.stringify(document, null, 2)}\n`,
  );
  writeFileSync(
    resolve(dir, `principals.${profile}.txt`),
    [
      `# Generated by \`pnpm kafka:acl:generate\` from TOPIC_PRODUCERS and TOPIC_CONSUMERS (RUN-006), profile ${profile}.`,
      '# Every principal the broker holds a SCRAM-SHA-512 credential for, besides the admin.',
      '# Each reads its password from KAFKA_SASL_PASSWORD_<NAME> (fleet-service -> _FLEET).',
      ...document.principals,
      '',
    ].join('\n'),
  );
  process.stdout.write(
    `kafka acl: ${profile}: ${document.principals.length} principals, ${document.acls.length} bindings\n`,
  );
}

const topics = contracts.brokerTopics();
writeFileSync(
  resolve(dir, 'topics.txt'),
  [
    '# Generated by `pnpm kafka:acl:generate` from TOPIC_PRODUCERS and TOPIC_CONSUMERS (RUN-006).',
    '# Every topic the bootstrap creates, and its kind: stream | retry | dead-letter | audit-trail.',
    ...topics.map((topic) => `${topic.name} ${topic.kind}`),
    '',
  ].join('\n'),
);
process.stdout.write(`kafka acl: ${topics.length} topics written to ${dir}\n`);
