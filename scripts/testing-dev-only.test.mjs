/**
 * scripts/testing-dev-only.mjs keeps the test signer in @rasta/testing out of
 * production in three layers: source reachability (resolved targets, in
 * scripts/testing-dev-only-source.mjs), the resolved production dependency
 * graph, and the built image's filesystem (the last runs in CI's
 * `containers` job; its scanner is tested here on fixture trees).
 */

const write = (root, files) => {
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
  }
};
const scratch = (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'testing-dev-only-test-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  return dir;
};

