-- When Keycloak may disagree with this user's rows, and when to re-project
-- them (ADR-060, write-ahead addendum, D-064).
--
-- Set, outside the transaction that failed, by every Keycloak writer of the
-- user whose write did not end cleanly:
--   * a write whose outcome is unknown (its deadline passed, the connection
--     broke after it was sent, a 5xx) may still be applied later, so the mark
--     is now + KEYCLOAK_WRITE_SETTLE_SECONDS. Until then a narrowing change of
--     the user is refused (503 KEYCLOAK_UNAVAILABLE): an older write could
--     land after it and leave Keycloak wider than the database.
--   * a write that landed in a transaction that then did not commit leaves
--     Keycloak narrower than the rows; the mark is now.
-- The membership expiry sweep re-projects every user whose mark has passed,
-- under the user lock, and that projection clears it.
--
-- Additive and nullable: a catalogue change, no table rewrite, every existing
-- user NULL (nothing to re-assert). No index: the sweep reads it once per
-- interval, and the user table is small; one can be built CONCURRENTLY later.
ALTER TABLE "user" ADD COLUMN "keycloak_reassert_at" TIMESTAMP(3);
